"""Run evaluation on the trained detection + segmentation checkpoints.

Produces (1) a printed summary table and (2) appends an entry to
``data/output/eval_results.md`` per ADR-0003.

Usage (defaults use trained models and val splits)::

    # Run with defaults (uses models/retinaface_final.pth + models/unet_final.pth)
    python -m src.eval

    # Run with custom paths
    python -m src.eval --detector-weights models/retinaface_final.pth \\
        --segmentor-weights models/unet_final.pth \\
        --detection-csv data/processed/detection/val/annotations.csv \\
        --detection-images data/processed/detection/val/images \\
        --segmentation-images data/processed/segmentation/val/images \\
        --segmentation-masks data/processed/segmentation/val/masks
"""

from __future__ import annotations

import argparse
import time
from datetime import datetime
from pathlib import Path

import numpy as np
import torch

from src.detection.eval import EvalEntry, evaluate_map
from src.detection.inference import RetinaFaceDetector
from src.segmentation.eval import compute_segmentation_metrics, numpy_metrics
from src.segmentation.inference import UNetSegmentor
from src.utils.io import ensure_dir


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Evaluate detector + segmentor.")
    parser.add_argument("--detector-weights", type=str, 
                        default="models/retinaface_final.pth",
                        help="Path to detection model (default: models/retinaface_final.pth)")
    parser.add_argument("--segmentor-weights", type=str, 
                        default="models/unet_final.pth",
                        help="Path to segmentation model (default: models/unet_final.pth)")
    parser.add_argument("--detection-csv", type=str, 
                        default="data/processed/detection/val/annotations.csv",
                        help="Detection annotations CSV (default: val split)")
    parser.add_argument("--detection-images", type=str, 
                        default="data/processed/detection/val/images",
                        help="Detection images directory (default: val split)")
    parser.add_argument("--segmentation-images", type=str, 
                        default="data/processed/segmentation/val/images",
                        help="Segmentation images directory (default: val split)")
    parser.add_argument("--segmentation-masks", type=str, 
                        default="data/processed/segmentation/val/masks",
                        help="Segmentation masks directory (default: val split)")
    parser.add_argument("--max-images", type=int, default=None)
    parser.add_argument("--device", type=str, default="cpu")
    parser.add_argument("--eval-results", type=str, default="data/output/eval_results.md")
    parser.add_argument("--det-iou-threshold", type=float, default=0.5)
    parser.add_argument("--seg-iou-threshold", type=float, default=0.5)
    return parser.parse_args()


def evaluate_segmentor(seg, images_dir: Path, masks_dir: Path, max_images: int | None = None) -> dict:
    """Compute IoU / Dice / pixel accuracy averaged over the test set."""
    import cv2

    # Support both .jpg and .png
    image_files = sorted(images_dir.glob("*.jpg")) + sorted(images_dir.glob("*.png"))
    if max_images is not None:
        image_files = image_files[:max_images]

    ious, dices, accs = [], [], []
    t0 = time.perf_counter()
    for img_path in image_files:
        mask_path = masks_dir / img_path.name
        if not mask_path.exists():
            continue
        img = cv2.imread(str(img_path), cv2.IMREAD_COLOR)
        gt_mask = cv2.imread(str(mask_path), cv2.IMREAD_GRAYSCALE)
        if img is None or gt_mask is None:
            continue
        pred = seg.predict_full(img)
        m = numpy_metrics(pred.mask, gt_mask)
        ious.append(m["iou"])
        dices.append(m["dice"])
        accs.append(m["pixel_acc"])
    elapsed = time.perf_counter() - t0
    n = len(ious)
    avg = {
        "iou": float(np.mean(ious)) if ious else 0.0,
        "dice": float(np.mean(dices)) if dices else 0.0,
        "pixel_acc": float(np.mean(accs)) if accs else 0.0,
        "n_images": n,
        "total_seconds": elapsed,
        "latency_ms_per_image": (elapsed / n * 1000) if n > 0 else 0.0,
    }
    return avg


def append_eval_entry(path: Path, model: str, dataset: str, rows: list[tuple[str, float, str, str]]) -> None:
    """Append a formatted evaluation entry following the skill template."""
    ensure_dir(path.parent)
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M")
    lines = [
        "",
        f"## [{timestamp}] {model} on {dataset}",
        "",
        "| Metric | Value | Target | Pass |",
        "|--------|-------|--------|------|",
    ]
    for metric, value, target, ok in rows:
        lines.append(f"| {metric} | {value} | {target} | {ok} |")
    lines.append("")
    lines.append("Notes: Auto-generated by `python -m src.eval`.")
    with open(path, "a", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def main() -> int:
    args = parse_args()
    device = torch.device(args.device)

    print("=== Detection eval ===")
    det = RetinaFaceDetector(weights=args.detector_weights, device=str(device), pretrained=False)
    det_metrics = evaluate_map(
        detector=det,
        csv_path=args.detection_csv,
        images_dir=args.detection_images,
        conf_threshold=0.05,
        nms_iou=0.5,
        iou_threshold=args.det_iou_threshold,
        max_images=args.max_images,
    )
    print(f"mAP@0.5   = {det_metrics['mAP']:.3f}")
    print(f"Recall@0.5= {det_metrics['recall']:.3f}")
    print(f"n_gt      = {det_metrics['n_gt']}")
    print(f"n_pred    = {det_metrics['n_pred']}")

    print("\n=== Segmentation eval ===")
    seg = UNetSegmentor(weights=args.segmentor_weights, device=str(device), image_size=128)
    seg_metrics = evaluate_segmentor(
        seg,
        images_dir=Path(args.segmentation_images),
        masks_dir=Path(args.segmentation_masks),
        max_images=args.max_images,
    )
    print(f"IoU          = {seg_metrics['iou']:.3f}")
    print(f"Dice         = {seg_metrics['dice']:.3f}")
    print(f"Pixel acc    = {seg_metrics['pixel_acc']:.3f}")
    print(f"n_images     = {seg_metrics['n_images']}")
    print(f"latency (ms) = {seg_metrics['latency_ms_per_image']:.1f}")

    rows = [
        ("mAP@0.5", f"{det_metrics['mAP']:.3f}", "≥ 0.90", "✅" if det_metrics["mAP"] >= 0.90 else "❌"),
        ("Recall@0.5", f"{det_metrics['recall']:.3f}", "≥ 0.95", "✅" if det_metrics["recall"] >= 0.95 else "❌"),
        ("IoU (face)", f"{seg_metrics['iou']:.3f}", "≥ 0.90", "✅" if seg_metrics["iou"] >= 0.90 else "❌"),
        ("Dice", f"{seg_metrics['dice']:.3f}", "≥ 0.95", "✅" if seg_metrics["dice"] >= 0.95 else "❌"),
        ("Pixel acc", f"{seg_metrics['pixel_acc']:.3f}", "≥ 0.97", "✅" if seg_metrics["pixel_acc"] >= 0.97 else "❌"),
        ("Latency CPU (ms)", f"{seg_metrics['latency_ms_per_image']:.1f}", "≤ 300", "✅" if seg_metrics["latency_ms_per_image"] <= 300 else "❌"),
        ("n images (seg)", str(seg_metrics["n_images"]), "—", "—"),
    ]
    append_eval_entry(Path(args.eval_results), "RetinaFace+U-Net (smoke train, 2-3 epochs, no-pretrained)", "processed/30-imgs subset", rows)
    print(f"\nAppended entry to {args.eval_results}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
